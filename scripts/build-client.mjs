/**
 * Build the browser half.
 *
 * DSH hands the browser exactly one file per plugin — whatever
 * `exports["./client"]` names — and that file must call
 * `window.__ModuleLoader__.load` exactly once, with no ESM left in it. So: bundle
 * src/client/ into an IIFE that receives the loader as a parameter, and have a
 * tiny hand-written wrapper put the result into the loader call.
 *
 * `react` stays external: the shell provides it, and bundling a second copy would
 * give the plugin its own hooks dispatcher (every render would throw).
 */
import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'

const OUT = 'lib/client.js'
const CLIENT_EXTERNAL = ['react', 'react/jsx-runtime']

const result = await build({
  entryPoints: ['src/client/index.js'],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: '__AnyAudioClient',
  target: ['chrome120'],
  platform: 'browser',
  external: CLIENT_EXTERNAL,
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
})

const bundled = result.outputFiles[0].text
if (/^\s*(import|export)\s/m.test(bundled)) {
  throw new Error('the bundle still contains ESM syntax; the loader cannot execute it')
}

const source = `/**
 * AnyAudio — browser half. GENERATED by scripts/build-client.mjs from src/client/.
 * Do not edit: change the sources under src/client/ and run \`npm run build\`.
 */
window.__ModuleLoader__.load({
  id: 'dsh-any-audio',
  factory: require => {
    const module = { exports: {} }
    const exports = module.exports
    ${bundled.replace(/^var __AnyAudioClient = /m, 'var __AnyAudioClient = ')}
    const mod = __AnyAudioClient
    exports.name = mod.name
    exports.apply = mod.apply
    exports.inject = mod.inject
    exports.__test = mod.__test
    return module.exports
  },
})
`

const calls = (source.match(/__ModuleLoader__\.load\(/g) || []).length
if (calls !== 1) throw new Error(`expected exactly one __ModuleLoader__.load call, found ${calls}`)

await writeFile(OUT, source)
const bytes = Buffer.byteLength(source)
console.log(`built ${OUT} (${(bytes / 1024).toFixed(1)} KB)`)
